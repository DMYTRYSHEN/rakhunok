/** Offline build only. No native modules or font parsing enter the Worker bundle. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { deflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { openSync } from 'fontkit';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);
const subsets = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'];
const sources = subsets.map((name) => new URL(`apps/pay/src/assets/fonts/manrope-${name}.woff2`, root));
const fonts = sources.map((path) => {
	const font = openSync(fileURLToPath(path));
	// Decode transformed WOFF2 glyf before enabling variation (fontkit's WOFF2
	// decoder lacks variation phantom-point methods on its temporary decoder).
	void font.glyphForCodePoint(32).path;
	font.variationCoords = [(600 - 200) / (800 - 200)];
	return font;
});
const alphabet = [...new Set([
	...Array.from({ length: 95 }, (_, i) => String.fromCodePoint(32 + i)),
	...Array.from({ length: 96 }, (_, i) => String.fromCodePoint(0x400 + i)),
	...'Ґґ₴’‘“”«»–—…№·€',
])];
const size = 96;
const glyphs = {};
const bitmaps = [];
let offset = 0;
for (const letter of alphabet) {
	const font = fonts.find((candidate) => candidate.hasGlyphForCodePoint(letter.codePointAt(0)));
	if (!font) throw new Error(`Missing font glyph: ${letter}`);
	const glyph = font.glyphForCodePoint(letter.codePointAt(0));
	const scale = size / font.unitsPerEm;
	const box = glyph.bbox;
	if (!Number.isFinite(box.minX)) {
		glyphs[letter] = [offset, 1, 1, 0, 0, glyph.advanceWidth * scale];
		bitmaps.push(Buffer.from([0]));
		offset++;
		continue;
	}
	const left = Math.floor(box.minX * scale) - 1;
	const top = Math.floor(-box.maxY * scale) - 1;
	const width = Math.max(1, Math.ceil(box.maxX * scale) - left + 1);
	const height = Math.max(1, Math.ceil(-box.minY * scale) - top + 1);
	const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><path fill="white" transform="translate(${-left} ${-top}) scale(${scale} ${-scale})" d="${glyph.path.toSVG()}"/></svg>`;
	const alpha = await sharp(Buffer.from(svg)).ensureAlpha().extractChannel(3).raw().toBuffer();
	glyphs[letter] = [offset, width, height, left, top, glyph.advanceWidth * scale];
	bitmaps.push(alpha);
	offset += alpha.length;
}
const logoSource = await readFile(new URL('logo – копія.svg', root), 'utf8');
// Preserve the supplied geometry exactly; the runtime tints the alpha mask emerald.
const logo = logoSource.replace('width="32" height="32"', 'width="64" height="68"');
const logoAlpha = await sharp(Buffer.from(logo)).ensureAlpha().extractChannel(3).raw().toBuffer();
const hashes = {};
for (const path of sources) hashes[path.pathname.split('/').at(-1)] = createHash('sha256').update(await readFile(path)).digest('hex');
hashes.logo = createHash('sha256').update(logoSource).digest('hex');
const generated = `// Generated by scripts/generate-telegram-invoice-art.mjs; do not edit.\n// Manrope: Copyright 2018 The Manrope Project Authors; SIL OFL 1.1 (telegram-invoice-art.OFL.txt).\nexport const TELEGRAM_LOGO_SVG = ${JSON.stringify(logoSource)};\nexport const TELEGRAM_ART_SOURCE_HASHES = ${JSON.stringify(hashes)};\nexport const TELEGRAM_FONT_SIZE = ${size};\nexport const TELEGRAM_GLYPHS: Record<string, readonly number[]> = ${JSON.stringify(glyphs)};\nexport const TELEGRAM_GLYPH_ALPHA_DEFLATE = ${JSON.stringify(deflateSync(Buffer.concat(bitmaps), { level: 9 }).toString('base64'))};\nexport const TELEGRAM_LOGO_ALPHA_DEFLATE = ${JSON.stringify(deflateSync(logoAlpha, { level: 9 }).toString('base64'))};\n`;
await writeFile(new URL('src/lib/features/dashboard/public-page/telegram-invoice-art.ts', root), generated);
console.log(`Generated ${alphabet.length} Manrope glyphs, ${offset} alpha bytes; module ${generated.length} bytes.`);