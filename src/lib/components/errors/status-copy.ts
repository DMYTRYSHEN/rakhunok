/** Only trusted, fixed copy reaches the error screen — never server error messages. */
export function statusCopy(value: number) {
	const status = Number.isInteger(value) && value >= 400 && value <= 599 ? value : 500;
	const copy =
		status === 404
			? ['Сторінку не знайдено', 'Перевірте адресу або поверніться на головну.']
			: status === 403
				? ['Доступ обмежено', 'Для цієї сторінки потрібен дозвіл. Поверніться на головну або зверніться до адміністратора.']
				: status === 401
					? ['Потрібен вхід', 'Щоб відкрити цю сторінку, увійдіть у свій обліковий запис через головну.']
					: status === 429
						? ['Забагато запитів', 'Зачекайте перед наступною спробою. Сторінка не оновлюється автоматично.']
						: status >= 500
							? ['Не вдалося відкрити сторінку', 'На сервері сталася помилка. Спробуйте пізніше або поверніться на головну.']
							: ['Запит не виконано', 'Не вдалося відкрити цю адресу. Перевірте посилання або поверніться на головну.'];
	return { status, title: copy[0], description: copy[1] };
}